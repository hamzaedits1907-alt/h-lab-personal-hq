/**
 * Generates supabase/migrations/0003_seed_starter_content.sql from src/content/seed.ts.
 * Run with: npm run seed:sql
 *
 * The generated SQL is idempotent and NON-DESTRUCTIVE: it only inserts when the
 * target table is empty (settings: when the row is absent), so re-running a
 * migration can never overwrite content the owner has edited.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { seedBlocks, seedProjects, seedSettings } from '../src/content/seed';

export function buildSeedSql(): string {
  const json = (v: unknown) => {
    const s = JSON.stringify(v);
    if (s.includes('$seed$')) throw new Error('seed text contains the dollar-quote tag');
    return `$seed$${s}$seed$::jsonb`;
  };
  const text = (v: string) => {
    if (v.includes("'")) return `'${v.replaceAll("'", "''")}'`;
    return `'${v}'`;
  };
  const s = seedSettings;
  const langs = `array[${s.languages.map(text).join(', ')}]`;

  const lines: string[] = [];
  lines.push('-- GENERATED by `npm run seed:sql` from src/content/seed.ts. Do not edit by hand.');
  lines.push('-- Inserts starter content only into EMPTY tables. Safe to re-run; never overwrites edits.');
  lines.push('');
  lines.push(`insert into public.hlab_site_settings (id, site_name, brand_text, contact_email, social_links, nav, footer, seo, ui,
  languages, default_language, is_published, accent, theme, background, animation)
values (1, ${text(s.siteName)}, ${text(s.brandText)}, null, ${json(s.socialLinks)}, ${json(s.nav)}, ${json(s.footer)}, ${json(s.seo)}, ${json(s.ui)},
  ${langs}, ${text(s.defaultLanguage)}, ${s.isPublished}, ${text(s.accent)}, ${text(s.theme)}, ${text(s.background)}, ${text(s.animation)})
on conflict (id) do nothing;`);
  lines.push('');

  lines.push('insert into public.hlab_content_blocks (id, type, anchor, admin_label, content, position, is_visible)');
  lines.push('select v.* from (values');
  lines.push(
    seedBlocks
      .map(
        (b) =>
          `  (${text(b.id)}::uuid, ${text(b.type)}, ${text(b.anchor)}, ${text(b.adminLabel)}, ${json(b.content)}, ${b.position}, ${b.isVisible})`,
      )
      .join(',\n'),
  );
  lines.push(') as v(id, type, anchor, admin_label, content, position, is_visible)');
  lines.push('where not exists (select 1 from public.hlab_content_blocks);');
  lines.push('');

  lines.push('insert into public.hlab_projects (id, slug, title, summary, description, status, tags, url, cover_media_id, position, is_visible)');
  lines.push('select v.* from (values');
  lines.push(
    seedProjects
      .map(
        (p) =>
          `  (${text(p.id)}::uuid, ${text(p.slug)}, ${text(p.title)}, ${json(p.summary)}, ${json(p.description)}, ${text(p.status)}, array[${p.tags.map(text).join(', ')}]::text[], null::text, null::uuid, ${p.position}, ${p.isVisible})`,
      )
      .join(',\n'),
  );
  lines.push(') as v(id, slug, title, summary, description, status, tags, url, cover_media_id, position, is_visible)');
  lines.push('where not exists (select 1 from public.hlab_projects);');
  lines.push('');
  return lines.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const out = fileURLToPath(new URL('../supabase/migrations/0003_seed_starter_content.sql', import.meta.url));
  writeFileSync(out, buildSeedSql(), 'utf8');
  console.log(`wrote ${out}`);
}
